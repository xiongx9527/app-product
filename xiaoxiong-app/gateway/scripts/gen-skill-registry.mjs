/**
 * 生成 skills/registry.generated.ts：扫描 skills/ 下所有 *_skill/ 目录，自动生成 import 与登记。
 *
 * 背景：build:bundle 用 esbuild 打成单文件，运行时没有目录结构，不能扫目录 / import.meta.glob，
 * 所以内置 skill 必须构建期静态 import。这个脚本把「加 skill = 手改 registry」变成
 * 「丢一个 xxx_skill/ 目录即可」，零手工登记。
 *
 * 约定：每个 *_skill/ 目录的 index.ts 导出一个 SkillModule 对象（名字随意，含 id/name/description/create）。
 * 生成代码用命名空间 import + 找含 create 的导出对象，不依赖具体导出名。
 */
import { readdirSync, existsSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const skillsDir = join(here, '..', 'src', 'service', 'skills')
const outFile = join(skillsDir, 'registry.generated.ts')

const dirs = readdirSync(skillsDir, { withFileTypes: true })
  .filter((e) => e.isDirectory() && e.name.endsWith('_skill') && existsSync(join(skillsDir, e.name, 'index.ts')))
  .map((e) => e.name)
  .sort()

const imports = dirs.map((d, i) => `import * as skillMod${i} from './${d}/index'`).join('\n')
const entries = dirs
  .map((_, i) => `const mod${i} = Object.values(skillMod${i}).find(\n  (v): v is SkillModule => !!v && typeof v === 'object' && 'id' in v && 'create' in v,\n)`)
  .join('\n')
const spread = dirs
  .map((_, i) => `  ...(mod${i} ? { [mod${i}.id]: mod${i} } : {}),`)
  .join('\n')

const content = `// GENERATED by scripts/gen-skill-registry.mjs — do not edit by hand.\n` +
  `// 新增 skill：往 skills/ 丢一个 xxx_skill/ 目录（其 index.ts 导出一个 SkillModule）后重新构建即可。\n` +
  `import type { SkillModule } from './types'\n` +
  `${imports}\n\n` +
  `${entries}\n\n` +
  `export const SKILL_MODULES: Record<string, SkillModule> = {\n${spread}\n}\n`

writeFileSync(outFile, content)
console.log(`[skills] 已生成 ${outFile}（${dirs.length} 个 skill: ${dirs.map((d) => d.replace(/_skill$/, '')).join(', ') || '无'}）`)
