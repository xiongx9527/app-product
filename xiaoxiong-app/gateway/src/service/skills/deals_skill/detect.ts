/**
 * 明显不是商品交易的固定搭配（成语 / 习语 / 口头禅），即便含交易词也不命中，
 * 避免「买卖不成仁义在」「不是东西」这类被误判。
 */
const NON_TRADE = /买卖不成|仁义在|不是东西|什么东西|搞什么东西|东西南北/

/**
 * 音视频 / 阅读内容类：这些是「点内容播放」而非「买商品」，按 AGENTS.md 的内容意图走，
 * 绝不能被商品词表劫持（如「推荐一部电影」「来段相声」「推荐本小说」）。
 */
const CONTENT_WORDS = /歌|歌曲|音乐|电影|电视剧|影片|综艺|动画|动漫|相声|评书|小品|戏曲|有声书|小说|评书|节目|视频|专辑|演唱会/

/** 识别结果：keyword 为搜索关键词；null 表示泛交易意图，走默认商品流。 */
export interface ProductQuery {
  keyword: string | null
}

/**
 * 识别商品意图。返回 null 表示不是商品类句子（应交给后续逻辑 / 大模型）。
 * 具体商品名优先于交易泛词：有「空调」就用「空调」搜，而不是退化成泛查询。
 */
export function detectProductQuery(text: string): ProductQuery | null {
  const t = text.trim()
  if (!t || NON_TRADE.test(t) || CONTENT_WORDS.test(t)) return null

  // 最长匹配，避免「笔记本电脑」被截成「电脑」当关键词
  let hit: string | null = null
  for (const w of PRODUCT_WORDS) {
    if (t.includes(w) && (hit === null || w.length > hit.length)) hit = w
  }
  if (hit) {
    // 品类词前的限定词（品牌/型号）要一起保留：「华为手机」不能只留「手机」，
    // 否则搜出 iPhone/小米（用户 2026-11-19 实锤「推荐华为手机却出 iPhone」）。
    const idx = t.indexOf(hit)
    const before = idx > 0 ? stripLeading(t.slice(0, idx)) : ''
    // 只并入短限定词（≤8字），避免把整句口语塞进关键词；品牌/型号一般很短
    const qualifier = before.replace(/[，,。.、\s]+$/g, '')
    const keyword = qualifier && qualifier.length <= 8 ? `${qualifier}${hit}` : hit
    return { keyword }
  }

  for (const w of TRADE_WORDS) {
    if (t.includes(w)) return { keyword: null }
  }
  return null
}

/** 剥掉品类词前的口语前缀（帮我/推荐/来/想买/个/款/一台…），留下品牌/型号限定词。 */
const LEADING_FILLERS = [
  // 第一人称买法（长词在前）：「我想买手机」必须先剥「我想买」，否则整句当搜索词搜不到
  '我想买', '我想入手', '我要买', '我要入手', '我买', '帮我买', '想买', '想入手',
  '帮我', '请帮我', '请', '麻烦', '给我', '推荐一下', '推荐', '来一下', '来',
  '买一个', '买个', '买一台', '买一部', '买', '搜一下', '搜', '查一下', '查询', '查',
  '有没有', '有什么', '有啥', '看一下', '看看', '要', '来个', '来一台', '来一部', '来一款',
  '最新款', '新款', '最新', '这个', '那个', '一款', '一台', '一部', '一下',
  '我', '一', '个', '款', '台', '部', '些', '下', '的', '好', '不错',
]
function stripLeading(s: string): string {
  let r = s.trim()
  let changed = true
  while (changed) {
    changed = false
    for (const w of LEADING_FILLERS) {
      if (r.startsWith(w)) { r = r.slice(w.length).trim(); changed = true }
    }
  }
  return r
}
