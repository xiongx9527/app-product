/** 兜底分类：匹配不到任何关键词时的通用话题标签。 */
export const FALLBACK_CATEGORY = '偏好'

/**
 * 把一条偏好短句归到确定性的话题标签。
 * 如「喜欢打乒乓球」→「运动」、「爱吃苹果」→「饮食」、「爱听周杰伦的歌」→「音乐」。
 * 匹配不到返回「偏好」（通用兜底，绝不用 LLM 抽出的残词）。
 */
export function classifyPreference(value: string): string {
  const v = (value ?? '').trim()
  if (!v) return FALLBACK_CATEGORY
  for (const rule of CATEGORY_RULES) {
    if (rule.words.some((w) => v.includes(w))) return rule.key
  }
  return FALLBACK_CATEGORY
}
