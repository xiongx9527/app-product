/**
 * 音乐控制指令识别：把用户口语映射到动作，绕开大模型，保证「说播放就真播」。
 * 只识别高置信度的控制词，避免与普通对话冲突（如「我想听你说」不会误触发）。
 */

export type MusicAction = 'play' | 'next' | 'pause' | 'resume' | 'stop' | 'recommend' | 'loop'

/**
 * 问句不应被「的歌 / 听歌」误判成点歌：像「这是谁唱的歌 / 这首歌叫什么」这类疑问，
 * 应交给大模型从「正在播放」上下文里回答，而不是去放一首新歌。
 * 只用无歧义疑问词（谁/什么/怎/吗/呢/？），不用「哪」（会误伤「播放哪吒」这类片名）。
 */
const MUSIC_QUESTION_RE = /[谁什么怎]|为什么|为何|吗|呢|\?|？/

const ACTION_PATTERNS: Array<{ action: MusicAction; re: RegExp }> = [
  // 暂停类：必须排最前——「暂停播放 / 暂停音乐」里的「暂停」先命中，避免被下面的
  // stop / play 抢匹配（用户反馈「暂停播放被关掉」就是 stop 的「停播」子串误中）。
  { action: 'pause', re: /(暂停|先停|停一下|歇一下)/ },
  // 停止类：排在 play 之前——「停止播放 / 关掉播放」含「播放」会触发 play 词，
  // 必须先于 play 命中停止；且不含「暂停」，不会与上面的暂停冲突。
  { action: 'stop', re: /(停止播放|关掉(音乐|播放)|别放了|停(掉)?音乐|关闭音乐|不(要|放)了)/ },
  // 循环播放类：排在 resume 之前——「再放一遍」里的「再放」会被 resume 抢中，
  // 必须先用带「遍」的循环模式截住。「N 遍」记遍数，缺省则整个当前曲循环一次（再播一遍）。
  { action: 'loop', re: /(循环播放|单曲循环|列表循环|重复播放|再放(一|这|那)?遍|循环(播|放)?|回放(一|这)?遍)/ },
  // 继续类：只认「继续 / 接着 / 恢复 / 再播放」，以及句末的「再放」（如「再放。」）。
  // 注意：不能写裸「再放」——「再放稻香」是按「再」关掉上下文的「全新点歌」，会被下面的
  // play 动词截住；裸「再放」只在该词就是句尾（不再跟歌名）时才算「继续播放」。
  { action: 'resume', re: /(继续(播放|放)?|接着(放|播|听)|恢复(播放)?|再播放|再放(?=$|[\s，。！？、]))/ },
  // 换一首 / 换个风格 / 下一首；评书/相声/影视类口语用「段 / 集 / 部 / 回」等量词，也要识别成换内容。
  // 「来首其它的 / 来个其它的」同样是「换一首」的意思（要一个不同的）。
  { action: 'next', re: /(换一?首|下一?首|换个?风格|换首|切歌|来点别的|换一?个风格|换台|来首(其它|别的|另外)|来个(其它|别的|另外)|换一?段|换段|下一?段|换一?集|换集|下一?集|换一?部|换部|换一?回|换回|再来一?段|来段别的)/ },
  // 推荐类：只列候选让用户选、绝不自动播放。必须有媒体/内容关键词（歌/音乐/曲/乐/音，
  // 以及视频/电视/电影/动画片/漫剧/戏/话剧/小品/评书/有声/小说/电台/广播/综艺/纪录片/比赛等）才进本分支，
  // 避免「推荐餐厅」之类被误判为点歌；排在 play 之前，避免「推荐」被 play 的「的歌」误中而直接播。
  { action: 'recommend', re: /(推荐|挑几首|选几首|来几首|找几首|有什么(好听)?|有哪些(好听)?|来点好听).*(歌|音乐|曲|乐|音|视频|电视|电视剧|电影|连续剧|剧场|动画片|动画|漫剧|动漫|戏|话剧|舞台剧|音乐剧|歌剧|小品|评书|评话|相声|快板|有声|读物|小说|故事|童话|电台|广播|综艺|节目|纪录片|晚会|比赛|赛事|直播|讲座|讲坛|课堂|公开课)/ },
  // 开始播放类（故意不含「我想听/想听」，避免「我想听你说」误触发）
  // 「周杰伦的歌」这类「X 的歌」也算点歌，好走「只给歌手→列候选」的分支。
  // 「唱 / 看」作为播放动词与「放 / 播放」同义（用户要求：唱、看也应识别为播放，
  // 「看电影 / 我想看动画片 / 看比赛」都要走播放），但「唱歌」是让助手自己唱/闲聊、不是点歌，
  // 「看见 / 看着 / 看情况 / 看样子 / 看我你他… / 看什么」不是看片请求，故「唱」「看」配负向先行守护。
  // 负向列表只收真正会误触发的少数前缀，不能用「比 / 如 / 因 / 为 / 和 …」这类常见字——
  // 否则「看比赛」（比）会被整体挡掉、反而识别不出来。
  // 「看」后跟的内容词（电视 / 电影 / 动画 / 相声 / 比赛 …）天然会进 B 站音轨抽取，本身没问题。
  // 「放<歌名>」（如「放稻香 / 再放稻香 / 想放稻香」）也识别为播放：放后直接跟歌名（中文），
  // 不接「首/个/歌/点/播/小/大/轻/低」等（那些是「放首歌 / 放大照片 / 把声音放小」等非点歌），
  // 且限定在句首或「再/想/要/给/帮/让」之后，避免「把声音放小」被误判成点歌。
  { action: 'play', re: /(播(放|歌)|来一?首|放一?首|点一?首|唱一?首|唱首|唱(?!歌)|放歌|听歌|整首|放点|看个|看部|看一?集|看一?部|我想看|看(?!见|着|清|楚|情|样|我|你|他|她|它|这|那|什|怎|办|能|否|懂|明)|的歌|的歌曲|(?:^|再|想|要|给|帮|让)放(?!一?首|歌|点|个|播|小|大|轻|低)[一-龥]+)/ },
]

/**
 * 从口语里解析显式「循环 N 遍」的遍数；返回 1 表示「未指定遍数，交回设置里的默认循环次数」。
 *  - 「循环播放3遍」→ 3；超上限按上限收敛，避免极端值拖垮播放。
 *  - 「再放一遍 / 再来一次」是明确「多播一次」的口语 → 固定 2。
 *  - 不带遍数的「循环播放 / 单曲循环 / 重复播放」→ 1，由上层落到设置里的「默认循环次数」
 *    （缺省 3），绝不在这里写死 2 把用户的 3 遍设置盖掉。
 *  - 普通点歌「放首歌」→ 1（不循环）。
 */
export function parseLoopCount(text: string, max = 99): number {
  const t = (text || '').trim()
  if (!t) return 1
  const m = t.match(/(\d+)\s*遍/)
  if (m) {
    const n = Number(m[1])
    if (Number.isFinite(n) && n >= 1) return Math.min(Math.floor(n), max)
    return 1
  }
  // 只有「再放一遍」这种明确「多一次」的口语固定为 2，其余不带遍数的循环词交回设置默认。
  if (/再(放|来|播).*(一遍|一次)/.test(t)) return 2
  return 1
}

/**
 * 纯口语「换个 / 换一个 / 换一段 / 再来一段 / 下一段」= 换内容。
 * 整句锚定，避免「换个方法」「换一个灯泡」这类普通对话被误判；
 * 这些说法此前会被 looksLikeBareMusicQuery 当成裸歌名去点歌（弹候选列表 / 报「没找到这首歌」）。
 */
const BARE_NEXT_RE =
  /^(换个|换一个|换一下|换一段|换段|再来一个|再来一段|下一段|换集|下一集|换部|换一回|来个别的|来段别的)$/

/** 返回匹配到的音乐动作；非音乐指令返回 null。 */
export function detectMusicCommand(text: string): MusicAction | null {
  const t = (text || '').trim()
  if (!t) return null
  if (BARE_NEXT_RE.test(t)) return 'next'
  for (const { action, re } of ACTION_PATTERNS) {
    if (re.test(t)) {
      // 问句里的「的歌 / 听歌」不该触发点歌：交给大模型回答「谁唱的 / 叫什么」，避免误放新歌。
      if (action === 'play' && MUSIC_QUESTION_RE.test(t)) return null
      return action
    }
  }
  return null
}

/**
 * 是否含「再」——用户的「再说一次 / 再放一首 / 再听」里的「再」表示「另来一次」，
 * 应当关掉跨轮上下文：点歌时不再按当前正在播放的歌手自动选版本，而是当作全新请求
 * （列候选 / 重新检索），避免「再放稻香」被当成「还是周杰伦的稻香」直接播。
 * 这是个通用原则：凡带「再」的请求都不依赖上一轮的歌手/歌名上下文。
 */
export function hasAgainMarker(text: string): boolean {
  return /再/.test(text || '')
}
